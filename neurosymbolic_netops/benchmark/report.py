"""Generate benchmark/results/REPORT.md from raw result files only (no hand-typed numbers).

python -m benchmark.report
"""

from __future__ import annotations

import json
from pathlib import Path

RES = Path(__file__).resolve().parent / "results"


def fmt(v):
    if v is None:
        return "-"
    if isinstance(v, dict) and "mean" in v:
        if v["mean"] is None:
            return "-"
        ci = v.get("ci95")
        return f"{v['mean']:.3f}" + (f" [{ci[0]:.2f}, {ci[1]:.2f}]" if ci else "")
    return str(v)


def main() -> None:
    out = ["# Benchmark Report (auto-generated by `python -m benchmark.report`)", "",
           "Every number below is read from files in `benchmark/results/`. 95% intervals are percentile "
           "bootstrap over scenarios (rule-based conditions are deterministic, so one trial each).", ""]
    for run in sorted(p for p in RES.iterdir() if (p / "summary.json").exists()):
        man = json.loads((run / "manifest.json").read_text())
        summ = json.loads((run / "summary.json").read_text())
        out += [f"## Run `{man['run_id']}`", "",
                f"commit `{man['git_sha'][:10]}` · conditions {man['conditions']} · scenarios {man['scenarios']} · "
                f"oracle **{man['oracle']}** · errors {man['errors']} · wall {man['wall_seconds']} s", ""]
        if man.get("skipped"):
            out += [f"**Skipped (not substituted):** {man['skipped']}", ""]
        out += ["| condition/split | n | top-1 | top-3 | F1 | fault recall | repaired | final intents OK | restored to baseline | unsafe deployed | rolled back | restores verified | gate rejections/incident | median total ms |",
                "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for k, s in summ.items():
            out.append(f"| {k} | {s['runs']} | {fmt(s['top1'])} | {fmt(s['top3'])} | {fmt(s['f1'])} | {fmt(s['fault_recall'])} | "
                       f"{fmt(s['repaired'])} | {fmt(s['final_intents_satisfied'])} | {fmt(s['restored_to_baseline'])} | "
                       f"{fmt(s['unsafe_deployed'])} | {fmt(s['rolled_back'])} | {s['rollback_restore_verified']} | "
                       f"{(s['gate_rejections'] or {}).get('mean', '-')} | {(s['total_ms'] or {}).get('median', '-')} |")
        out += ["", "Outcomes: " + "; ".join(f"{k}: {v['outcomes']}" for k, v in summ.items()), ""]
        lat = ["| condition/split | detection ms | diagnose ms | plan ms | verify ms | execute ms | tool calls | LLM calls | prompt tok | completion tok |",
               "|---|---|---|---|---|---|---|---|---|---|"]
        for k, s in summ.items():
            g = lambda x: (s[x] or {}).get("median", "-")
            lat.append(f"| {k} | {g('detection_ms')} | {g('diagnose_ms')} | {g('plan_ms')} | {g('verify_ms')} | {g('execute_ms')} | "
                       f"{g('tool_calls')} | {g('llm_calls')} | {g('prompt_tokens')} | {g('completion_tokens')} |")
        out += ["Median per-incident cost:", ""] + lat + [""]
    p = RES / "differential_local_vs_batfish.json"
    if p.exists():
        d = json.loads(p.read_text())
        s = d["summary"]
        out += ["## Local model vs real Batfish (single-fault differential)", "",
                f"Agreement on the set of violated intents: **{s['agree']}/{s['cases']}** (run before the "
                "`bgp-peer-consistency` intent existed; that ir_static intent now covers the MD5/activation gaps).", "",
                "| template | cases | agree |", "|---|---|---|"]
        out += [f"| {t} | {v['cases']} | {v['agree']} |" for t, v in s["by_template"].items()]
        import statistics
        out += ["", f"Median verification time: Batfish {statistics.median(r['batfish_ms'] for r in d['rows']):.0f} ms, "
                    f"local {statistics.median(r['local_ms'] for r in d['rows']):.1f} ms.", ""]
    p = RES / "translation_validation.json"
    if p.exists():
        d = {k: v for k, v in json.loads(p.read_text()).items() if not k.startswith("_")}
        out += ["## Vendor translation - behavioural check in Batfish", "",
                f"Equivalent on all intents: **{sum(v['equivalent_on_intents'] for v in d.values())}/{len(d)}** networks.", "",
                "| target/network | equivalent | IOS violated | target violated | parse issues |", "|---|---|---|---|---|"]
        out += [f"| {k} | {v['equivalent_on_intents']} | {v['ios_violated']} | {v['target_violated']} | {v['target_parse_issues']} |" for k, v in d.items()]
        out.append("")
    p = RES / "causal_discovery_pc.json"
    if p.exists():
        d = json.loads(p.read_text())
        out += ["## Causal discovery (PC, synthetic SCM, mean of 5 seeds)", "",
                "| setting | PC skeleton precision | PC skeleton recall | SHD | correlation precision | spurious CPU edges (corr) | spurious CPU edges (PC) |",
                "|---|---|---|---|---|---|---|"]
        for k, v in d.items():
            m = v["mean_over_5_seeds"]
            out.append(f"| {k} | {m['pc_skeleton_precision']} | {m['pc_skeleton_recall']} | {m['shd_skeleton']} | "
                       f"{m['correlation_precision']} | {m['spurious_cpu_associations_by_correlation']} | {m['spurious_cpu_edges_by_pc']} |")
        out.append("")
    p = Path(__file__).resolve().parent.parent / "models" / "syslog_classifier_metrics.json"
    if p.exists():
        m = json.loads(p.read_text())
        out += ["## Edge syslog classifier", "",
                f"held-out phrasing accuracy {m['heldout_phrasing']['accuracy']} (macro-F1 {m['heldout_phrasing']['macro_f1']}); "
                f"message-only (mnemonic removed) accuracy {m['heldout_phrasing_message_only']['accuracy']} "
                f"(macro-F1 {m['heldout_phrasing_message_only']['macro_f1']}); model {m['model_bytes']} bytes; "
                f"{m['heldout_phrasing']['latency_us_per_line']} us/line.", ""]
    demos = sorted((Path(__file__).resolve().parent.parent / "demos" / "output").glob("*.json"))
    if demos:
        out += ["## Demonstration runs (single runs - anecdotal, not a measurement)", "",
                "| demo | reasoning | outcome | attempts | LLM calls | tokens (provider-reported) |", "|---|---|---|---|---|---|"]
        for p in demos:
            r = json.loads(p.read_text())
            u = r.get("llm_usage") or {}
            out.append(f"| {p.stem} | {r['modes']['diagnosis']} | {r['outcome']} | "
                       f"{[a['disposition'] for a in r['attempts']]} | {u.get('calls', 0)} | {u.get('total_tokens', 0)} |")
        out.append("")
    (RES / "REPORT.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote", RES / "REPORT.md")


if __name__ == "__main__":
    main()
